const LanguageContext = createContext(null)

function initialLanguage() {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    return stored === 'en' ? 'en' : 'vi'
  } catch {
    return 'vi'
  }
}

function interpolate(template, variables = {}) {
  return Object.entries(variables).reduce(
    (value, [key, replacement]) => value.replaceAll(`{${key}}`, String(replacement)),
    template,
  )
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(initialLanguage)

  const value = useMemo(() => ({
    language,
    setLanguage: (nextLanguage) => setLanguage(nextLanguage === 'en' ? 'en' : 'vi'),
    t: (key, variables) => interpolate(messages[language][key] || messages.vi[key] || key, variables),
  }), [language])

  useEffect(() => {
    document.documentElement.lang = language
    document.title = messages[language]['site.title']
    document.querySelector('meta[name="description"]')?.setAttribute('content', messages[language]['site.description'])
    try {
      window.localStorage.setItem(STORAGE_KEY, language)
    } catch {
      // The interface remains usable when browser storage is unavailable.
    }
  }, [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider.')
  return context
}
